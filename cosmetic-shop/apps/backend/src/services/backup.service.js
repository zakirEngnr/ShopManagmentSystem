import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PrismaClient } from '@prisma/client';
import { PrismaLibSql } from '@prisma/adapter-libsql';
import { env } from '../config/env.js';
import { logger } from '../utils/logger.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const BACKEND_ROOT = path.dirname(path.dirname(__dirname)); // apps/backend

const BACKUP_DIR = (() => {
  const raw = process.env.BACKUP_DIR;
  if (!raw || raw === '') return path.join(BACKEND_ROOT, 'backups');
  return path.isAbsolute(raw) ? raw : path.resolve(BACKEND_ROOT, raw);
})();

const RETENTION_DEFAULT = 30;
const BACKUP_KEEP = (() => {
  const raw = Number(process.env.BACKUP_KEEP);
  return Number.isFinite(raw) && raw >= 1 ? raw : RETENTION_DEFAULT;
})();

const BACKUP_COPY_DIR = process.env.BACKUP_COPY_DIR || '';

const DB_FILE_SUFFIX_REGEX = /^shop-\d{8}-\d{6}\.db$/;

function nowTimestamp() {
  const d = new Date();
  const pad = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}${pad(d.getMonth() + 1)}${pad(d.getDate())}-${pad(d.getHours())}${pad(d.getMinutes())}${pad(d.getSeconds())}`;
}

function backupFileName() {
  return `shop-${nowTimestamp()}.db`;
}

function resolveDbFilePath() {
  const url = env.DATABASE_URL;
  if (!url || !url.startsWith('file:')) {
    throw new Error(
      'VACUUM INTO requires a local file database; remote libSQL backups are not supported by this script.',
    );
  }
  return path.resolve(url.replace(/^file:/, ''));
}

export function assertLocalDatabase() {
  resolveDbFilePath();
}

function ensureBackupDir() {
  fs.mkdirSync(BACKUP_DIR, { recursive: true });
}

function listBackupFiles() {
  ensureBackupDir();
  const names = fs.readdirSync(BACKUP_DIR);
  const backups = [];
  for (const name of names) {
    if (!DB_FILE_SUFFIX_REGEX.test(name)) continue;
    const full = path.join(BACKUP_DIR, name);
    let stat;
    try {
      stat = fs.statSync(full);
    } catch {
      continue;
    }
    backups.push({ filename: name, path: full, mtime: stat.mtimeMs, size: stat.size });
  }
  backups.sort((a, b) => b.mtime - a.mtime);
  return backups;
}

function escapeSqlString(value) {
  return String(value).replace(/'/g, "''");
}

function prismaForFile(fileUrl) {
  const adapter = new PrismaLibSql({ url: fileUrl });
  return new PrismaClient({ adapter });
}

export async function verifyBackup(filePath) {
  let prisma;
  try {
    const fileUrl = `file:${filePath}`;
    prisma = prismaForFile(fileUrl);
    const rows = await prisma.$queryRawUnsafe('PRAGMA integrity_check');
    const first = rows[0];
    const result = String(first && (first.integrity_check !== undefined ? first.integrity_check : Object.values(first)[0]));
    if (result !== 'ok') {
      throw new Error(`integrity check failed: ${result}`);
    }
    return true;
  } catch (err) {
    try { fs.unlinkSync(filePath); } catch {}
    logger.warn(`backup verification failed for ${filePath}: ${err.message}`);
    throw err;
  } finally {
    if (prisma) {
      try { await prisma.$disconnect(); } catch {}
    }
  }
}

export async function createBackup() {
  assertLocalDatabase();
  ensureBackupDir();

  const dbFile = resolveDbFilePath();
  try {
    fs.accessSync(dbFile, fs.constants.R_OK);
  } catch {
    throw Object.assign(new Error('Database file not found'), { status: 404 });
  }

  const filename = backupFileName();
  const dest = path.join(BACKUP_DIR, filename);

  // VACUUM INTO refuses to overwrite an existing output file. Filenames are
  // timestamp-generated by this module, so removing a pre-existing same-name
  // file (edge case: two backups in the same second) is safe.
  try { fs.unlinkSync(dest); } catch {}

  const escaped = escapeSqlString(dest);
  let admin;
  try {
    admin = prismaForFile(`file:${dbFile}`);
    await admin.$executeRawUnsafe(`VACUUM INTO '${escaped}'`);
  } catch (err) {
    throw Object.assign(new Error(`Backup creation failed: ${err.message}`), { status: 500 });
  } finally {
    if (admin) { try { await admin.$disconnect(); } catch {} }
  }

  const ok = await verifyBackup(dest);
  if (!ok) {
    throw new Error(`Backup verification failed for ${filename}`);
  }

  const stat = fs.statSync(dest);

  if (BACKUP_COPY_DIR) {
    try {
      fs.mkdirSync(BACKUP_COPY_DIR, { recursive: true });
      fs.copyFileSync(dest, path.join(BACKUP_COPY_DIR, filename));
    } catch (err) {
      logger.warn(`Could not copy backup to ${BACKUP_COPY_DIR}: ${err.message}`);
    }
  }

  return {
    id: filename,
    filename,
    size: stat.size,
    createdAt: new Date().toISOString(),
  };
}

export async function listBackups() {
  return listBackupFiles().map(({ filename, size, mtime }) => ({
    id: filename,
    filename,
    size,
    createdAt: new Date(mtime).toISOString(),
  }));
}

export function enforceRetention() {
  const backups = listBackupFiles();
  const toDelete = backups.slice(BACKUP_KEEP);
  let deleted = 0;
  for (const { path: filePath } of toDelete) {
    try { fs.unlinkSync(filePath); deleted += 1; } catch {}
  }
  return deleted;
}

export async function runScheduledBackup() {
  try {
    const backups = listBackupFiles();
    const now = Date.now();
    const oldestAllowed = now - 24 * 60 * 60 * 1000;
    const due = backups.length === 0 || backups[0].mtime < oldestAllowed;
    if (due) {
      const created = await createBackup();
      enforceRetention();
      logger.info(`Scheduled backup created: ${created.filename}`);
    }
  } catch (err) {
    logger.warn(`Scheduled backup skipped: ${err.message}`);
  }
}

export function startBackupScheduler() {
  void runScheduledBackup();
  const interval = setInterval(() => { void runScheduledBackup(); }, 24 * 60 * 60 * 1000);
  if (interval.unref) interval.unref();
  return interval;
}

export default {
  createBackup,
  listBackups,
  verifyBackup,
  enforceRetention,
  runScheduledBackup,
  startBackupScheduler,
  assertLocalDatabase,
  get BACKUP_DIR() {
    return BACKUP_DIR;
  },
};
