// Report writers: a machine readable JSON report and a human readable SQL plan.
import fs from 'node:fs';
import path from 'node:path';
import { CATEGORY } from './plan.mjs';

export function writeJsonReport(outDir, report) {
  fs.mkdirSync(outDir, { recursive: true });
  const file = path.join(outDir, 'reconciliation-report.json');
  fs.writeFileSync(file, `${JSON.stringify(report, null, 2)}\n`);
  return file;
}

export function writeSqlPlan(outDir, plan, { target, history = [] } = {}) {
  fs.mkdirSync(outDir, { recursive: true });
  const file = path.join(outDir, 'reconciliation-plan.sql');
  const lines = [];
  lines.push('-- ============================================================================');
  lines.push('-- SQLite reconciliation plan (generated by scripts/db-reconcile)');
  lines.push(`-- target: ${target}`);
  lines.push('--');
  lines.push('-- REVIEW THIS FILE BEFORE RUNNING ANY OF IT.');
  lines.push('-- The tool never drops a table, a column or a row; every statement below');
  lines.push('-- is either additive or a table rebuild that copies all rows first.');
  lines.push('-- ============================================================================');
  lines.push('');

  let n = 0;
  for (const step of plan) {
    n += 1;
    lines.push(`-- ---------------------------------------------------------------------------`);
    lines.push(`-- [${step.id}] ${step.category}: ${step.action}`);
    lines.push(`-- reason: ${step.rationale}`);
    if (step.preservedExtraColumns?.length) {
      lines.push(`-- preserved extra columns: ${step.preservedExtraColumns.join(', ')}`);
    }
    if (step.preservedExtraIndexes?.length) {
      lines.push(`-- preserved extra indexes: ${step.preservedExtraIndexes.join(', ')}`);
    }
    if (step.preservedExtraConstraints?.length) {
      lines.push(`-- preserved extra foreign key constraints: ${step.preservedExtraConstraints.length}`);
    }
    if (step.dependentViews?.length) {
      lines.push(
        `-- dependent views (kept working by legacy_alter_table): ${step.dependentViews.join(', ')}`,
      );
    }
    for (const check of step.prechecks ?? []) {
      lines.push(`-- PRE-CHECK  ${check.description}`);
      lines.push(`--            ${check.sql}`);
    }
    for (const check of step.postchecks ?? []) {
      lines.push(`-- POST-CHECK ${check.description}`);
      lines.push(`--            ${check.sql}`);
    }
    if (!step.sql.length) {
      lines.push('-- (no SQL: report only)');
    }
    for (const statement of step.sql) {
      lines.push(String(statement).trim().endsWith(';') ? String(statement).trim() : `${String(statement).trim()};`);
    }
    lines.push('');
  }

  if (history.length) {
    lines.push('-- ============================================================================');
    lines.push('-- MIGRATION HISTORY (report only - the tool never changes history records)');
    lines.push('-- ============================================================================');
    for (const item of history) {
      lines.push(`-- [${item.id}] ${item.migration ?? '(database)'} - ${item.state} (${item.severity})`);
      lines.push(`-- finding: ${item.finding}`);
      for (const action of item.recommendedActions) lines.push(`-- ${action}`);
      lines.push('');
    }
  }

  fs.writeFileSync(file, `${lines.join('\n')}\n`);
  return file;
}

export function planCategoryCounts(plan) {
  const counts = {};
  for (const step of plan) counts[step.category] = (counts[step.category] ?? 0) + 1;
  return counts;
}

export function renderSummary(report) {
  const lines = [];
  const p = (s = '') => lines.push(s);
  p('========================================================================');
  p(' SQLite reconciliation report');
  p('========================================================================');
  p(` target              : ${report.target.path}`);
  p(` target sha256       : ${report.target.sha256}`);
  p(` mode                : ${report.mode}`);
  p(` generated at        : ${report.generatedAt}`);
  p(` expected schema     : ${report.expected.source}`);
  p(`   tables/columns    : ${report.expected.tables} / ${report.expected.columns}`);
  p(`   unique/regular ix : ${report.expected.uniqueIndexes} / ${report.expected.regularIndexes}`);
  p(`   foreign keys      : ${report.expected.foreignKeys}`);
  p('');
  p(' classification (before)');
  for (const [k, v] of Object.entries(report.classification.before.counts)) {
    p(`   ${k.padEnd(12)} ${v}`);
  }
  if (report.classification.after) {
    p(' classification (after)');
    for (const [k, v] of Object.entries(report.classification.after.counts)) {
      p(`   ${k.padEnd(12)} ${v}`);
    }
  }
  p('');
  p(' plan');
  const counts = planCategoryCounts(report.plan);
  for (const [k, v] of Object.entries(counts)) p(`   ${k.padEnd(20)} ${v}`);
  p('');
  if (report.history.length) {
    p(' migration history');
    for (const item of report.history) {
      p(`   [${item.severity}] ${item.migration ?? '(database)'}: ${item.finding}`);
    }
  } else {
    p(' migration history: nothing to report');
  }
  p('');
  p(' data preservation');
  if (!report.data) {
    p('   (no write operation was performed)');
  } else {
    p(`   fingerprints compared : ${report.data.tablesCompared}`);
    p(`   row count changes     : ${report.data.rowCountChanges}`);
    p(`   data loss             : ${report.data.dataLoss}`);
    for (const d of report.data.deltas ?? []) {
      p(`   - ${d.table}: ${d.kind}${d.changed ? ` (${d.changed.map((c) => c.column).join(', ')})` : ''}`);
    }
  }
  p('');
  p(` output files         : ${report.output.json}`);
  p(`                       ${report.output.sql}`);
  return lines.join('\n');
}
